def test_RecruitmentPageVacancyCleanup(shared_page):
    print("\nStarting test_RecruitmentPageVacancyCleanup transaction")
    recruitment_page = RecruitmentPage(shared_page)
    print("Will click on Recruitment menu")
    recruitment_page.click_recruitment_menu()
    print("Clicked on the Recruitment menu - will now click on the Vacancies tab")
    recruitment_page.click_vacancies_submenu()
    try:
        print("Clicked on the vacancies submenu/tab - will now search for the record that will be deleted")
        recruitment_page.click_vacancies_job_title_dropdown(timeout=5000)
        print("Clicked on the job title dropdown - will select Software Engineer option")
        recruitment_page.select_vacancies_software_engineer_job_title_option(timeout=5000)
        print("Selected the Software Engineer option - will now select the Hiring Manager")
        recruitment_page.click_vacancies_hiring_manager_dropdown_menu(timeout=5000)
        recruitment_page.select_vacancies_hiring_manager_charles_carter_option(timeout=5000)
        print("Selected Charles Carter as the hiring manager - will now click on the Search button")
        recruitment_page.click_vacancies_search_button()
        print("Clicked on the Search button - will click on the Search result")
        print("Checking if there is a record to delete")
        expect(recruitment_page.vacancies_vacancy_record_found).to_be_visible(timeout=15000)
        print("There's a record to delete - proceeding...")
        recruitment_page.click_vacancies_search_result()
        print("Clicked on the Search result - will click on the Delete button")
        recruitment_page.click_vacancies_delete_vacancy_button()
        print("Clicked on the Delete button - will click on the confirmation message")
        recruitment_page.click_vacancies_confirm_delete_button()
        expect(recruitment_page.vacancies_delete_successful_message).to_be_visible(timeout=15000)
    except:
        print("There was no record to delete - ending the test")
    print("\nEnded test_RecruitmentPageVacancyCleanup transaction")

